import { describe, expect, it } from "vitest";

import { PLAYERS_OPENING_QUERY } from "../../components/players/playersOpeningQuery";
import { readStyleGuideOptions } from "../styleGuide/styleGuideOptions";
import { fixtureHandlers } from "./fixtureAnswers";
import {
  familiarity,
  gameState,
  playersPage,
  playersPageQuery,
  positionGroups,
  ratingTiers,
  squad,
  squadFitness,
  staff,
  teamsDirectory,
} from "./fixture.generated";
import { UNANSWERED } from "./harnessIpc";
import { profileCase } from "./profileCases";

const handlers = fixtureHandlers(readStyleGuideOptions(""), "en");
const club = gameState.manager.team_id;

describe("fixture answers", () => {
  /**
   * Given a harness URL asking for the cards view (`?view=cards`), and one asking for nothing
   * When a page asks for the settings
   * Then the list view is cards for the first and the game's default, table, for the second, so a
   *      screenshot or layout check can open a list in either view without clicking the switch.
   */
  it("answers the list view the URL asked for", () => {
    const cards = fixtureHandlers(readStyleGuideOptions("?view=cards"), "en");
    expect(cards.get_settings({})).toMatchObject({ settings: { list_view: "cards" } });
    expect(handlers.get_settings({})).toMatchObject({ settings: { list_view: "table" } });
  });

  /** Given the user's club, when its squad is asked for, then the fixture's squad comes back. */
  it("answers for the user's club", () => {
    expect(handlers.get_squad({ teamId: club })).toBe(squad);
  });

  /**
   * Given the Squad and Tactics pages asking how each of the club's players stands at every position
   * When the harness answers get_familiarity
   * Then it gives the fixture's projection, generated by the same ofm_core function the command
   *      reads: a row for every squad player, each graded at every position.
   */
  it("answers the club's familiarity", () => {
    expect(handlers.get_familiarity({})).toBe(familiarity);
    expect(familiarity.players.map((row) => row.player_id).sort()).toEqual(
      squad.map((player) => player.id).sort(),
    );
    for (const row of familiarity.players) {
      expect(Object.keys(row.by_position)).toHaveLength(positionGroups.length);
    }
  });

  /**
   * Given Home or Squad asking for the squad's fitness (the backend's counts and each player's
   * condition band), when the harness answers, then it gives the fixture's, generated by the same
   * ofm_core function the command reads.
   */
  it("answers the squad's fitness", () => {
    expect(handlers.get_squad_fitness({})).toBe(squadFitness);
    // A real summary: a band for every squad player, not an empty or missing answer.
    expect(Object.keys(squadFitness.statuses).sort()).toEqual(squad.map((p) => p.id).sort());
    const statuses: Record<string, { label_key: string }> = squadFitness.statuses;
    expect(statuses[squad[0].id].label_key).toMatch(/^be\.condition\./);
  });

  /**
   * Given Squad colouring its ratings (RatingChip, #952), when it asks for the rating tiers, then
   * the harness gives the backend's table, generated from the ofm_core function the command
   * returns: one tier for every rating from 0 to 99, Rest at the bottom and S at the top.
   */
  it("answers the rating tiers with the backend's table", () => {
    expect(handlers.get_rating_tiers({})).toBe(ratingTiers);
    expect(ratingTiers).toHaveLength(100);
    expect(ratingTiers[0]).toBe("Rest");
    expect(ratingTiers[99]).toBe("S");
    expect(new Set(ratingTiers)).toEqual(new Set(["S", "A", "B", "Rest"]));
  });

  /**
   * Given Squad's position badges (PositionBadge, #986) asking which group each position is in,
   * when the harness answers, then it gives the backend's table, generated from the ofm_core
   * function the command returns: every position, each in one of the four groups.
   */
  it("answers the position groups with the backend's table", () => {
    expect(handlers.get_position_groups({})).toBe(positionGroups);
    expect(positionGroups.find((entry) => entry.position === "Goalkeeper")?.group).toBe(
      "Goalkeeper",
    );
    expect(new Set(positionGroups.map((entry) => entry.group))).toEqual(
      new Set(["Goalkeeper", "Defender", "Midfielder", "Forward"]),
    );
  });

  /**
   * Given another club, when its squad, standing or finances are asked for, then the fixture
   * declines: it only holds the user's club, and must not pass it off as another's.
   */
  it("declines another club", () => {
    for (const command of ["get_squad", "get_club_league_standing", "get_finance_snapshot"]) {
      expect(handlers[command]({ teamId: "another-club" })).toBe(UNANSWERED);
    }
  });

  /** Given no team id, when the finances are asked for, then they are the user's club's, as in Rust. */
  it("treats a missing team id as the user's club for finances", () => {
    expect(handlers.get_finance_snapshot({ teamId: null })).not.toBe(UNANSWERED);
  });

  /**
   * Given player ids, one of them unknown, when contract stages are asked for, then only the
   * known players' stages come back, as Rust leaves an unknown id out.
   */
  it("answers contract stages only for the players asked about", () => {
    const [first] = squad;
    const stages = handlers.get_contract_warning_stages({ playerIds: [first.id, "nobody"] });
    expect(Object.keys(stages as object)).toEqual([first.id]);
  });
});

describe("world list answers", () => {
  /**
   * Given the query the Players page opens with, and the one page_fixture.rs builds by hand (Rust
   * can't import the page's)
   * When the fixture is read
   * Then they are the same query, so a change to either fails here, not as an unanswered page.
   */
  it("was generated for the query the Players page opens with", () => {
    expect(playersPageQuery).toEqual(PLAYERS_OPENING_QUERY);
  });

  /**
   * Given the Players page opening, when it asks for its first page with the query it opens with,
   * then the fixture's page comes back: a full page of the world's players, best first, from more
   * clubs than the user's.
   */
  it("answers the Players page's opening query", () => {
    const answer = handlers.get_players_page({ query: { ...playersPageQuery } });
    expect(answer).toBe(playersPage);
    expect(playersPage.items).toHaveLength(playersPageQuery.page_size);
    expect(playersPage.total).toBeGreaterThan(playersPageQuery.page_size);
    const ratings = playersPage.items.map((player) => player.ovr);
    expect(ratings).toEqual([...ratings].sort((a, b) => b - a));
    expect(new Set(playersPage.items.map((player) => player.team_id)).size).toBeGreaterThan(1);
  });

  /**
   * Given the opening query with its keys in another order (the page declares them in its own
   * order; the fixture's come out of Rust sorted)
   * When the Players page asks
   * Then it is still the same query, and answered.
   */
  it("answers the opening query whatever the order of its keys", () => {
    const reordered = Object.fromEntries(Object.entries(playersPageQuery).reverse());
    expect(Object.keys(reordered)).not.toEqual(Object.keys(playersPageQuery));
    expect(handlers.get_players_page({ query: reordered })).toBe(playersPage);
  });

  /**
   * Given any other query (a search, another page), when the Players page asks, then the harness
   * declines rather than answer it with the opening page.
   */
  it("declines a Players query the fixture wasn't generated for", () => {
    expect(handlers.get_players_page({ query: { ...playersPageQuery, search: "Smith" } })).toBe(
      UNANSWERED,
    );
    expect(handlers.get_players_page({ query: { ...playersPageQuery, page: 2 } })).toBe(UNANSWERED);
  });

  /** Given the Teams page with no search, then the directory holds every club in the world. */
  it("answers the Teams directory", () => {
    expect(handlers.get_teams_directory({ query: { search: null } })).toBe(teamsDirectory);
    const listed = teamsDirectory.regions.flatMap((region) =>
      region.leagues.flatMap((league) => league.teams.map((card) => card.team.id)),
    );
    expect(listed.sort()).toEqual(gameState.teams.map((team) => team.id).sort());
  });

  /** Given a search on the Teams page, then the harness declines rather than ignore the search. */
  it("declines a Teams search", () => {
    expect(handlers.get_teams_directory({ query: { search: "Celtic" } })).toBe(UNANSWERED);
  });

  /**
   * Given the Staff page for the user's club, then its staff and the hiring market come back;
   * for another club, the harness declines.
   */
  it("answers the user's club's staff only", () => {
    expect(handlers.get_staff({ teamId: club })).toBe(staff);
    expect(staff.team_staff.length).toBeGreaterThan(0);
    expect(staff.team_staff.every((member) => member.team_id === club)).toBe(true);
    expect(staff.available_staff.length).toBeGreaterThan(0);
    expect(handlers.get_staff({ teamId: "another-club" })).toBe(UNANSWERED);
  });
});

describe("fixture answers: the profile's knowledge of players", () => {
  const profileHandlers = (variant: "own" | "retired") =>
    fixtureHandlers(readStyleGuideOptions(""), "en", variant);
  const someOtherPlayerId = (not: string) => gameState.players.find((p) => p.id !== not)?.id ?? "";

  /**
   * Given the profile open on the club's own player
   * When the knowledge of that player is asked for
   * Then it is the case's: the club's own
   */
  it("answers the knowledge of the player the profile is open on", () => {
    const { playerId } = profileCase("own");
    expect(profileHandlers("own").get_player_knowledge({ playerIds: [playerId] })).toEqual({
      [playerId]: { kind: "own" },
    });
  });

  /**
   * Given the profile open on one player
   * When the page also asks about another player who is in the world
   * Then the fixture has no answer (Rust answers every player in the game), so the harness lists it
   *      as unanswered instead of letting the page read the missing entry as "unknown"
   */
  it("declines a request that includes another active player", () => {
    const { playerId } = profileCase("own");
    const other = someOtherPlayerId(playerId);
    expect(profileHandlers("own").get_player_knowledge({ playerIds: [playerId, other] })).toBe(
      UNANSWERED,
    );
    expect(profileHandlers("own").get_player_knowledge({ playerIds: [other] })).toBe(UNANSWERED);
  });

  /**
   * Given the profile open on a retired player, who is no player of the world
   * When his knowledge is asked for
   * Then the answer is empty, as Rust leaves out an id no player has, and it is not a decline
   */
  it("leaves a retired player out of the answer, deliberately", () => {
    const { playerId } = profileCase("retired");
    expect(profileHandlers("retired").get_player_knowledge({ playerIds: [playerId] })).toEqual({});
  });

  /**
   * Given the own player's profile asking for his last three matches
   * When the match history is answered
   * Then it is the three most recent of the five he has, as the page's `limit` asks for
   */
  it("answers the match history up to the limit the page asked for", () => {
    const { playerId, recentMatches } = profileCase("own");
    const answer = profileHandlers("own").get_player_match_history({ playerId, limit: 3 });
    expect(answer).toEqual(recentMatches.slice(0, 3));
  });

  /**
   * Given the profile open on the injured player, and on the club's own player
   * When the active game is asked for
   * Then the injured case's game holds his injury (the patch laid over him) and the other case's is
   *      the fixture's game itself
   */
  it("lays the case's patch over the player in the active game", () => {
    const injured = profileCase("injured");
    const patched = fixtureHandlers(readStyleGuideOptions(""), "en", "injured").get_active_game(
      {},
    ) as {
      players: { id: string; injury: unknown }[];
    };

    expect(patched.players.find((player) => player.id === injured.playerId)?.injury).toMatchObject({
      days_remaining: 12,
    });
    expect(fixtureHandlers(readStyleGuideOptions(""), "en", "own").get_active_game({})).toBe(
      gameState,
    );
  });
});
